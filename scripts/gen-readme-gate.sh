# Regenerate the README's block of gate output from a real build.
#
# Run from the repository root:
#
#     nix develop --command scripts/gen-readme-gate.sh --print   # to stdout
#     nix develop --command scripts/gen-readme-gate.sh --write   # into README.md
#
# ## Why this exists
#
# `codec-drift-closure` design D2. The README quotes the `axiom gate:` lines that
# `lake build` prints. That quotation is a **figure** — the spec calls it a
# "quotation of an assertable output" — and a hand-transcribed figure rots while
# the gate it quotes stays green. Measured at this change's start: **3 of the 14
# committed lines were stale at HEAD** (the `constant kinds`, `stated footprints`
# and `recursion-principle promotion` lines), while the prose above them said
# "pasted verbatim from a green build".
#
# So the quotation is generated by the run it describes, and `checks.gate-lines`
# regenerates it and diffs — the same mechanism `checks.mirror` uses for
# `gen-axioms.lean`, chosen over a marked region because it needs no new
# convention inside a markdown file (design D2's stated preference). The region
# markers remain, so a reader can see which lines are generated.
#
# ## What is canonical
#
# The **build log** is canonical; the README is derived. `--print` writes the
# block to stdout, `--write` replaces the region in `README.md` between the
# `<!-- BEGIN GENERATED gate-lines -->` / `<!-- END GENERATED gate-lines -->`
# markers. The markers are HTML comments so they do not render.
#
# ## Elision
#
# Long lines are elided at `ELIDE_AT` characters with `…`, because a
# 400-character line is unreadable in a terminal and the full text is one
# `lake build` away. **The elision is lossy, and that bounds what the check can
# see**: `checks.gate-lines` compares a fresh regeneration against the committed
# block, so it catches a stale *prefix* — a moved count — but not a change past
# character `ELIDE_AT` of a long line. Widening the limit widens what the check
# can see; this is stated here rather than left for a reader to discover.
set -euo pipefail

ELIDE_AT=200
BEGIN='<!-- BEGIN GENERATED gate-lines -->'
END='<!-- END GENERATED gate-lines -->'
EXPECTED_GATE_LINES=14

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$root"

# The gate lines, as `lake build` prints them, with the
# `info: <file>:<line>:<col>: ` prefix stripped so the block reads the way the
# README always read it. The gate emits lines beginning
# `info: Axioms.lean:<n>:0: axiom gate: …`.
emit_block() {
  local log lines
  log=$(mktemp)
  # shellcheck disable=SC2064
  trap "rm -f '$log'" RETURN
  lake build Axioms > "$log" 2>&1

  # **A denominator for this check itself.** If `lake build` stops emitting the
  # gate — an `Axioms.lean` that fails to compile, a build that replayed
  # everything — the grep below yields zero lines, and a zero-line block would
  # "match" a zero-line README region vacuously. So the count is asserted, and
  # `EXPECTED_GATE_LINES` must move together with the README's prose count and
  # with any arm added or removed.
  lines=$(grep -c '^info: Axioms.lean:[0-9]*:[0-9]*: axiom gate:' "$log" || true)
  if [ "$lines" -ne "$EXPECTED_GATE_LINES" ]; then
    echo "gen-readme-gate: expected $EXPECTED_GATE_LINES gate lines, the build printed $lines" >&2
    echo "gen-readme-gate: the gate did not run, or an arm was added/removed —" >&2
    echo "gen-readme-gate: update EXPECTED_GATE_LINES and the README prose count together." >&2
    tail -40 "$log" >&2
    return 1
  fi

  printf '```\n'
  grep '^info: Axioms.lean:[0-9]*:[0-9]*: axiom gate:' "$log" \
    | sed 's/^info: Axioms\.lean:[0-9]*:[0-9]*: //' \
    | while IFS= read -r line; do
        if [ "${#line}" -gt "$ELIDE_AT" ]; then
          printf '%s…\n' "${line:0:$ELIDE_AT}"
        else
          printf '%s\n' "$line"
        fi
      done
  printf '```\n'
}

case "${1:---print}" in
  --print)
    emit_block
    ;;
  --write)
    block=$(emit_block)
    BEGIN="$BEGIN" END="$END" BLOCK="$block" python3 <<'PY'
import os

begin, end, block = os.environ["BEGIN"], os.environ["END"], os.environ["BLOCK"]
path = "README.md"
src = open(path).read()
i, j = src.index(begin), src.index(end)
head, tail = src[: i + len(begin)], src[j:]

# **Idempotence is load-bearing, not cosmetic.** `--write` must reproduce the
# file it was run on byte-for-byte, or `checks.gate-lines` — which regenerates and
# diffs — fails forever. An earlier version of this script wrote one newline
# before the END marker while the committed file had a blank line there, so the
# check reported a one-line difference on an otherwise green tree. Found by
# mutation-testing the check against a hand-perturbed README, which is what §2.2
# asks for. The separator is therefore owned by this script, not by the file:
# exactly one blank line after BEGIN and exactly one before END.
assert head.endswith(begin), "the BEGIN marker must be the last thing in `head`"
assert tail.startswith(end), "the END marker must be the first thing in `tail`"
open(path, "w").write(head + "\n\n" + block + "\n" + tail.lstrip("\n"))
PY
    echo "gen-readme-gate: rewrote the generated region in README.md" >&2
    ;;
  *)
    echo "usage: $0 [--print|--write]" >&2
    exit 2
    ;;
esac
